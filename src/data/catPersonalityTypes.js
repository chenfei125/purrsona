// 计算猫性格结果
export const calculateCatPersonality = (answers, questions) => {
  if (!answers || !questions || answers.length === 0) return null;

  let socialScore = 0;
  let activeScore = 0;
  let emotionScore = 0;

  answers.forEach((answer, index) => {
    const question = questions[index];
    if (!question || !question.mapping) return;
    
    question.mapping.forEach(map => {
      const value = answer || 0;
      if (map.axis === 'social') socialScore += value * map.direction;
      if (map.axis === 'active') activeScore += value * map.direction;
      if (map.axis === 'affection') emotionScore += value * map.direction;
    });
  });

  // 根据分数判断类型
  if (socialScore < -3 && emotionScore < 0) {
    return CAT_PERSONALITY_TYPES.independent;
  }
  
  if (socialScore > 3 || emotionScore > 5) {
    return CAT_PERSONALITY_TYPES.affectionate;
  }
  
  if (activeScore > 3 || socialScore > 0) {
    return CAT_PERSONALITY_TYPES.social;
  }
  
  if (emotionScore < -3) {
    return CAT_PERSONALITY_TYPES.aggressive;
  }

  return CAT_PERSONALITY_TYPES.independent;
};
